export function t(
  key: I18nKey | string,
  lang: Lang = "uz",
  vars?: Record<string, string | number>
): string {
  let text = translations[lang]?.[key] || translations["uz"]?.[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return text;
}
